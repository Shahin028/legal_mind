# BEST MATCH (RAG)  — with minimum score threshold
# =====================================

MIN_SCORE = 0.25  # below this the query is unrelated to any law

def best_match(query: str) -> str:
    q_vec  = model.encode([query], normalize_embeddings=True)
    scores = np.dot(embeddings, q_vec.T).flatten()
    index  = int(np.argmax(scores))
    top_score = float(scores[index])

    print(f"[RAG] query='{query}'  top_score={top_score:.4f}  threshold={MIN_SCORE}")

    if top_score < MIN_SCORE:
        print(f"[RAG] below threshold - no relevant law")
        return "No relevant Indian law found for this query."

    law = laws_data[index]
    print(f"[RAG] matched -> {law.get('law')}  {law.get('section')}  '{law.get('title')}'")
    return f"""
Law: {law.get("law")}
Section: {law.get("section")}
Title: {law.get("title")}
Content: {law.get("content")}
"""

