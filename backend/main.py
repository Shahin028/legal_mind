@app.post("/chatbot")
def conversational_chatbot(data: dict):
    messages = data.get("messages", [])
    if not messages:
        return {"reply": "No messages found.", "context_used": "No context"}
    
    last_user_info = messages[-1] if len(messages) > 0 else {}
    last_user_msg = last_user_info.get("content", "") if last_user_info.get("role") == "user" else ""
    context_text = "No context found"
    
    if last_user_msg:
        print(f"[CHATBOT] extracting context for latest msg: {last_user_msg[:50]}...")
        context_text = best_match(last_user_msg)
        
        system_prompt = """You are LegalMind, a highly experienced and professional Indian Lawyer and Legal Consultant.
Your goal is to provide helpful, authoritative, and empathetic legal guidance. 

1.  **Context-Awareness**: If the user's message is a casual greeting (like "hi", "hello", "how are you"), respond politely as a welcoming lawyer. Do NOT provide a full legal assessment for simple greetings.
2.  **Legal Persona**: Always use a formal and professional tone. Address the user with respect.
3.  **Legal Inquiries**: If a legal question or scenario is presented, provide a detailed response. 
    - Use the provided "Indian Law Context" if relevant.
    - If the context is missing, use your internal knowledge of Indian Laws to provide a broad assessment.
4.  **Instructions**: When providing legal advice, provide clear, step-by-step instructions throughout your response. Number your instructions so the user knows exactly what to do next.
5.  **Structure (for Legal Queries)**: Use headings like ### Legal Assessment, ### Relevant Provisions, and ### Step-by-Step Instructions ONLY when answering legal questions.
6.  **Disclaimer**: Always include a concise legal disclaimer at the end of every response."""
        
        openrouter_messages = [{"role": "system", "content": system_prompt}]
        openrouter_messages.extend(messages[:-1]) # add history
        
        # Create a more structured input for the LLM
        if "No relevant Indian law found" in context_text:
            embellished_msg = f"User Question: {last_user_msg}\n\n(Note: No specific entry was found in the local law database for this part of the conversation. Please respond based on your training data if it is a legal question, or respond casually if it is a greeting.)"
        else:
            embellished_msg = f"Specified Indian Law Context:\n{context_text}\n\nUser Question: {last_user_msg}"
            
        openrouter_messages.append({"role": "user", "content": embellished_msg})
        
        payload = {
            "model": "liquid/lfm-2.5-1.2b-thinking:free",
            "messages": openrouter_messages,
            "temperature": 0.4,
            "max_tokens": 2048,
        }
        
        url = "https://openrouter.ai/api/v1/chat/completions"
        headers = {
            "Authorization": f"Bearer {OPENROUTER_KEY}",
            "HTTP-Referer": "http://localhost:3000",
            "X-Title": "LegalMind",
            "Content-Type": "application/json"
        }
        
        try:
            r = requests.post(url, headers=headers, json=payload, timeout=60)
            if r.status_code == 200:
                msg_content = r.json()["choices"][0]["message"].get("content")
                reply = msg_content if msg_content is not None else ""
                return {"reply": reply, "context_used": context_text}
            else:
                return {"reply": f"LLM Error (HTTP {r.status_code}): {r.text[:200]}", "context_used": context_text}
        except Exception as e:
            return {"reply": f"Connection Error: {e}", "context_used": context_text}
    else:
        return {"reply": "Please send a valid message.", "context_used": "None"}

