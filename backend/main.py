@app.get("/search")
def search(query: str):
    print(f"[SEARCH] query='{query}'")

    try:  
        if not query.strip():
            print("[SEARCH] empty query, returning []")
            return {"results": []}

        q_vec  = model.encode([query], normalize_embeddings=True)
        scores = np.dot(embeddings, q_vec.T).flatten()

        results = []
        for i, score in enumerate(scores):
            if score > 0.35:
                results.append({
                    "law":     laws_data[i].get("law",     ""),
                    "section": laws_data[i].get("section", ""),
                    "title":   laws_data[i].get("title",   ""),
                    "content": laws_data[i].get("content", ""),
                    "keywords": laws_data[i].get("keywords", []),
                    "score":   float(score),
                })

        results = sorted(results, key=lambda x: x["score"], reverse=True)
        top = results[:5]
        print(f"[SEARCH] {len(top)} results (threshold 0.35):")
        for r in top:
            print(f"  score={r['score']:.4f}  {r['law']} {r['section']}  '{r['title']}'")
        return {"results": top}

    except Exception as e:
        print(f"[SEARCH] ERROR: {e}")
        return {"results": [], "error": str(e)}

