@app.get("/legal-news")
def legal_news():
    print("[NEWS] fetching legal news...")
    try:
        # Require legal keywords AND "India"
        url = (
            f"https://newsapi.org/v2/everything"
            f"?q=(\"Supreme Court\" OR \"High Court\" OR law OR legal OR judgement OR verdict OR lawyer OR advocate) AND India"
            f"&searchIn=title,description"
            f"&language=en"
            f"&sortBy=publishedAt"
            f"&apiKey={NEWS_API_KEY}"
        )
        response = requests.get(url, timeout=10)
        print(f"[NEWS] status_code={response.status_code}")

        news_data = response.json()

        if news_data.get("status") != "ok":
            msg = news_data.get("message", "Unknown error from NewsAPI")
            print(f"[NEWS] ❌ NewsAPI returned status='{news_data.get('status')}'  message={msg}")
            print(f"[NEWS] full response: {json.dumps(news_data)[:400]}")
            return {"news": [], "error": msg}

        news_list = []
        for article in news_data.get("articles", [])[:10]:
            title = article.get("title", "")
            # NewsAPI sometimes returns "[Removed]" articles — skip them
            if not title or title == "[Removed]":
                continue
            news_list.append({
                "title":  title,
                "source": article.get("source", {}).get("name"),
                "url":    article.get("url"),
                "image":  article.get("urlToImage"),
            })

        print(f"[NEWS] returning {len(news_list)} articles")
        return {"news": news_list}

    except Exception as e:
        print(f"[NEWS] ERROR: {e}")
        return {"news": [], "error": str(e)}

